/* USART1接收缓冲区队列指针初始化
 * 参数: 无
 * 返回值: 无
 */
void U1Rx_PtrInit(void)
{
  U1CB.URxDataIN = &U1CB.URxDataPtr[0];     // 指定收货员去拿URxDataPtr[]卡片里的信息
  U1CB.URxDataOUT = &U1CB.URxDataPtr[0];    // 指定分拣员去拿URxDataPtr[]卡片里的信息
  U1CB.URxDataEND = &U1CB.URxDataPtr[NUM - 1];
  U1CB.URxDataIN->start = U1_RxBuff;
  U1CB.URxCounter = 0;
}

/* USART1的printf函数重写
 * 参数: 无
 * 返回值: 无
 */
void u1_printf(char *format, ...)
{
  uint16_t i;
  va_list listdata;
  va_start(listdata, format);
  vsprintf((char *)U1_TxBuff, format, listdata);
  va_end(listdata);

  for(i = 0; i < (uint16_t)strlen((const char*)U1_TxBuff); i++)
  {
    HAL_UART_Transmit(&huart1, &U1_TxBuff[i], 1, 100);
  }
  while(__HAL_UART_GET_FLAG(&huart1, UART_FLAG_TC) == RESET);
}
